package  Writer;

our $VERSION='0.05';

sub new{
   my ($class,$w)=@_;
   my $self= {w     => $w,
              cursor=> new Vector2(50,50),
              colour=>"white",
              size  =>2,
              lw    =>1,
              };
   bless $self,$class;
   $self->{font}=$self->baseFont();
   return $self;
}

sub charLineSet{
  my ($self,$char)=@_;
  my $plines=[];
  foreach my $line (@{$self->{font}->{$char}}){
      my $pts=[];
      foreach my $point(@$line) {
         my $v=new Vector2($point->[0],$point->[1]*2);
         push @$pts,$v->mul($self->{size})->add($self->{cursor});
        #print $v->{x},"-",$v->{y}, "   #   #" ,  $pts->[-1]->{x},":",$pts->[-1]->{y},"\n";
      }
      push @$plines,$pts;
      #$self->{w}->polyline($pts,$self->{lw});
  }
  return $plines
}

sub printChar{
  my ($self,$char)=@_;
  my $plines=$self->charLineSet($char);
  foreach (@$plines){
    $self->{w}->polyline($_,$self->{lw});
  }
}

sub strLineSet{
  my ($self,$string)=@_;
  my @chrs=split //,$string;
  my $plines=[];
  my $position=new Vector2($self->{cursor});
  foreach (@chrs){
    if ($_=~/\R/){
      $self->{cursor}=new Vector2([$position->{x},$self->{cursor}->{y}-6*$self->{size}] );
    }
    else{
    #  $self->printChar($_);
      push @$plines,@{$self->charLineSet($_)};
      $self->{cursor}->{x}+=3*$self->{size};
    }
  }
  $self->{cursor}=$position;
  return $plines;
}

sub printString{
  my ($self,$string)=@_;
  my $plines=$self->strLineSet($string);
  foreach (@$plines){
    $self->{w}->polyline($_,$self->{lw});
  }
}

sub setSize{
  my ($self,$size,)=@_;
  $self->{size}=$size;
  return $self;
}

sub setThickness{
  my ($self,$lw,)=@_;
  $self->{lw}=$lw;
  return $self;
}

sub at{
  my ($self,$position)=@_;
  $self->{cursor}=new Vector2($position);
  return $self;
}

